import { createHash } from 'node:crypto';
import { ChannelError } from '../../../shared/contracts.mjs';

const hash = value => createHash('sha256').update(Buffer.isBuffer(value) ? value : typeof value === 'string' ? value : JSON.stringify(value)).digest('hex');

/** Revalidate only the in-memory result of this exact generation. This path is
 * intentionally separate from ordinary library resolve/prepare permissions.
 */
export function generatedChatImageSegment(library, accountId, selected) {
  const asset = selected?.asset, generation = selected?.generated ?? asset?.generation;
  if (!generation || !asset || asset.kind !== 'image')
    throw new ChannelError('IMAGE_GENERATION_SAVE', '当前生图结果不属于此回复');
  const saved = library.resolveAsset(accountId, asset.id, { enabledOnly: false });
  const stored = Buffer.from(library.getContent(accountId, asset.id, { enabledOnly: false }).data, 'base64');
  const bytes = Buffer.isBuffer(generation.bytes) ? generation.bytes : stored;
  const digest = hash(bytes);
  if ((saved.contentSha256 || saved.id) !== digest || saved.mediaType !== generation.mediaType ||
      !['image/png', 'image/jpeg'].includes(generation.mediaType))
    throw new ChannelError('ASSET_CONTENT_INVALID', '本轮生成图片与素材库中的原件不匹配，未发送');
  return { type: 'image', data: { base64: bytes.toString('base64'), mediaType: generation.mediaType,
    name: saved.name || generation.fileName } };
}

/** Persist the actual generated bytes before send. The pending entry is visible
 * only to its requester until a server ACK is attached. A tombstone or disabled
 * collection is authoritative: this helper never re-imports/deletes/recreates it.
 */
export async function captureChatGeneratedImage(images, scope, record, generated, assertAllowed = () => {}, signal = new AbortController().signal) {
  if (!generated || !Buffer.isBuffer(generated.bytes) || !['image/png', 'image/jpeg'].includes(generated.mediaType))
    throw new ChannelError('IMAGE_MEMORY_INVALID', '聊天生图没有可归档的 PNG/JPEG 原图');
  const input = { accountId: scope.accountId, chatType: scope.chatType, peerId: scope.peerId,
    senderId: record.senderId, collection: 'generated' };
  assertAllowed(); signal.throwIfAborted();
  const initial = images.load(input);
  if (!initial.settings.enabled) return null;
  const jobId = hash([scope.accountId, record.chatType, record.peerId, record.key]).slice(0, 12);
  const generation = {
    jobId,
    fileName: generated.fileName || ('AI-' + jobId + (generated.mediaType === 'image/jpeg' ? '.jpg' : '.png')),
    requesterId: record.senderId || scope.accountId,
    deliveryState: 'not-confirmed',
    serverMessageIds: [],
    ...(generated.providerName ? { providerName: String(generated.providerName).slice(0, 4000) } : {}),
    ...(generated.model ? { model: String(generated.model).slice(0, 4000) } : {}),
    prompt: String(generated.prompt || '').slice(0, 4000),
  };
  const attachment = { type: 'image', resourceId: 'chat-generated:' + jobId + ':' + hash(generated.bytes), generation };
  const generatedAt = Number.isSafeInteger(generated.generatedAt) && generated.generatedAt > 0 ? generated.generatedAt
    : typeof images.now === 'function' ? images.now() : Date.now();
  const entry = { messageId: 'chat-image-' + jobId, senderId: scope.accountId,
    senderName: '微信助手', direction: 'outgoing', text: '图片生成要求：' + generation.prompt,
    time: generatedAt };
  const item = await images.capture(input, entry, attachment,
    { data: generated.bytes.toString('base64'), mediaType: generated.mediaType, quality: 'original' }, signal,
    { generation: initial.generation });
  if (!item) return null;
  signal.throwIfAborted(); assertAllowed();
  // capture may return null after a concurrent clear, revoke or disable.
  const saved = images.content(input, item.id);
  images.assertReference(saved.reference);
  return { input, id: item.id, reference: saved.reference, generation: item.generation ?? generation,
    fileName: generation.fileName };
}

export function resolveChatGeneratedImageMemory(images, scope, generation) {
  if (!generation || !/^[a-f0-9]{64}$/.test(generation.imageMemoryId || '') || !generation.requesterId) return null;
  const input = { accountId: scope.accountId, chatType: scope.chatType, peerId: scope.peerId,
    senderId: generation.requesterId, collection: 'generated' };
  try {
    const saved = images.content(input, generation.imageMemoryId);
    images.assertReference(saved.reference);
    return { input, id: generation.imageMemoryId, reference: saved.reference, generation };
  } catch { return null; }
}

/** Attach only a detailed ACK for this exact media bubble. A missing/ambiguous
 * receipt leaves it unconfirmed, and never re-captures pixels or revives tombstones.
 */
export function acknowledgeChatGeneratedImage(images, captured, { deliveryParts = [], planIndex, sentAt, serverMessageIds = [] } = {}) {
  if (!captured || !Number.isSafeInteger(sentAt) || sentAt <= 0) return false;
  const parts = deliveryParts.filter(part => part.planIndex === planIndex && part.type === 'image');
  if (parts.length !== 1 || parts[0].state !== 'acknowledged' || typeof parts[0].serverMessageId !== 'string' ||
      !parts[0].serverMessageId || parts[0].serverMessageId === '0' || !serverMessageIds.includes(parts[0].serverMessageId)) return false;
  const generation = { ...captured.generation, deliveryState: 'sent', sentAt, serverMessageIds: [parts[0].serverMessageId] };
  try {
    // Verify the saved original digest, scope, enabled setting and deletion mark
    // immediately before metadata mutation. updateGeneration itself respects the
    // tombstone and returns without recreating a deleted index item.
    images.assertReference(captured.reference);
    images.updateGeneration(captured.input, captured.id, generation);
    images.assertReference(captured.reference);
    return true;
  } catch { return false; }
}
