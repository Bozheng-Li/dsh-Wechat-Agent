test('public image downloader validates addresses, redirects, file bytes and size before storing', async t => {
  const f = fixture(t); const opened = [];
  const body = bytes => ({ async *[Symbol.asyncIterator]() { yield bytes; }, destroy() {} });
  const options = { lookupImpl: async () => [{ address: '8.8.8.8', family: 4 }], open: async url => { opened.push(url.href); return { status: 200, headers: {}, body: body(f.png) }; } };
  const result = await downloadPublicImage('https://images.example/a.png', signal(), options); assert.deepEqual(result.bytes, f.png);
  for (const address of ['127.0.0.1', '10.1.2.3', '169.254.169.254', '192.168.1.1', '::1', '::ffff:127.0.0.1', 'fc00::1']) assert.equal(publicImageAddress(address), false);
  await assert.rejects(downloadPublicImage('http://127.0.0.1/image.png', signal(), options), /内网/); assert.equal(opened.length, 1);
  await assert.rejects(downloadPublicImage('https://images.example/redirect', signal(), { ...options, open: async () => ({ status: 302, headers: { location: 'http://169.254.169.254/secret' }, body: body(Buffer.alloc(0)) }) }), /内网/);
  await assert.rejects(downloadPublicImage('https://images.example/big', signal(), { ...options, open: async () => ({ status: 200, headers: { 'content-length': 11 * 1024 * 1024 }, body: body(Buffer.alloc(0)) }) }), /10 MiB/);
  await assert.rejects(downloadPublicImage('https://images.example/html', signal(), { ...options, open: async () => ({ status: 200, headers: {}, body: body(Buffer.from('<html>not an image</html>')) }) }));
});

