const assert = require('node:assert/strict');
module.exports = async function verifyExecutionTraces({ evaluate, waitFor, click, clickText, input, fixture, screenshot, assertLayout, check, resize, downloads, sendInput, emulateReducedMotion }) {
  const { ids } = await fixture('traceFixture');
  await click('[data-testid="nav-traces"]');
  await waitFor(() => document.querySelectorAll('.wa-trace-list-item').length > 0);
  assert.equal(await evaluate(() => document.querySelectorAll('[aria-label="任务轨迹分类"] [role="tab"]').length), 9);
  await click('[data-trace-id="' + ids.conversation + '"]');
  await waitFor(() => document.querySelector('.wa-trace-detail h2')?.textContent.includes('整理今天的讨论'));
  await waitFor(() => document.querySelectorAll('.wa-graph-node-group').length === 5);
  assert.equal(await evaluate(() => document.querySelectorAll('.wa-graph-node-step').length), 0);
  await assertLayout('execution trace desktop'); await screenshot('execution-traces-desktop-light', 'light'); await screenshot('execution-traces-desktop-dark', 'dark');
  check('nine compact categories show counts and a bounded relationship graph initially groups all execution steps');
  const hoverPoint = await evaluate(() => { const r = document.querySelector('[data-group-id="model"]').getBoundingClientRect(); return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + r.height / 2) }; });
  sendInput({ type: 'mouseMove', ...hoverPoint });
  await waitFor(() => document.querySelectorAll('.wa-graph-connection[data-highlighted="true"]').length === 1);
  assert(await evaluate(() => document.querySelectorAll('.wa-graph-node-wrap[data-muted="true"]').length > 0));
  await screenshot('execution-traces-branch-focus-light', 'light');
  sendInput({ type: 'mouseMove', x: 30, y: 30 });
  await waitFor(() => document.querySelectorAll('.wa-graph-connection[data-highlighted="true"]').length === 0);
  await evaluate(() => document.querySelector('[data-group-id="tool"]').focus({ preventScroll: true }));
  await waitFor(() => document.querySelector('[data-node-id="group-tool"]').dataset.active === 'true');
  await evaluate(() => document.activeElement.blur());
  check('pointer hover and keyboard focus highlight the associated branch while other nodes recede');
  await input('[aria-label="筛选轨迹步骤"]', 'tool');
  await click('[data-group-id="tool"]'); await waitFor(() => document.querySelectorAll('.wa-graph-node-step').length === 1);
  await click('.wa-graph-node-step');
  await waitFor(() => document.querySelector('.wa-trace-inspector')?.textContent.includes('确认过的项目进展'));
  assert.equal(await evaluate(() => document.body.textContent.includes('TRACE_UI_SECRET')), false);
  assert(await evaluate(() => document.querySelector('.wa-trace-inspector').textContent.includes('已隐藏')));
  await screenshot('execution-traces-node-detail-light', 'light');
  await click('[aria-label="关闭步骤详情"]');
  await waitFor(() => !document.querySelector('.wa-trace-inspector'));
  assert(await evaluate(() => document.activeElement.matches('.wa-graph-node-step')));
  await input('[aria-label="筛选轨迹步骤"]', 'all');
  await clickText('任务输入与结果', '.wa-trace-detail-tabs');
  await waitFor(() => document.querySelector('.wa-trace-detail').textContent.includes('合成记录，仅用于本地界面验证。'));
  await clickText('本次配置', '.wa-trace-detail-tabs');
  await waitFor(() => document.querySelector('.wa-trace-detail').textContent.includes('trace-model'));
  check('step filters expose actual inputs, outputs and configuration while secret values stay redacted');
  await clickText('导出本次轨迹', '.wa-trace-detail');
  const deadline = Date.now() + 16000;
  while (!downloads().length && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 70));
  assert.equal(downloads().length, 1); assert.equal(downloads()[0].state, 'completed');
  assert.equal(downloads()[0].data.trace.id, ids.conversation);
  assert(downloads()[0].data.steps.some(step => step.kind === 'model'));
  assert(!JSON.stringify(downloads()[0].data).includes('TRACE_UI_SECRET'));
  check('the export button downloads a complete JSON trace with its referenced payloads and no stored credentials');
  await click('[data-testid="traces-tab-work"]'); await click('[data-trace-id="' + ids.work + '"]');
  await waitFor(() => document.querySelector('.wa-trace-loaded')?.textContent.includes('100 /'));
  const beforeHeight = await evaluate(() => document.querySelector('.wa-traces-split').getBoundingClientRect().height);
  await clickText('继续加载步骤'); await waitFor(() => !document.querySelector('.wa-trace-loaded button'));
  await click('[data-group-id="stage"]'); await waitFor(() => document.querySelectorAll('.wa-graph-node-step').length === 8);
  const firstIds = await evaluate(() => [...document.querySelectorAll('.wa-graph-node-step')].map(node => node.dataset.stepId));
  await clickText('下一组', '.wa-trace-branch-pages');
  const nextIds = await evaluate(() => [...document.querySelectorAll('.wa-graph-node-step')].map(node => node.dataset.stepId));
  assert(nextIds.every(id => !firstIds.includes(id)));
  assert.equal(await evaluate(() => document.querySelector('.wa-traces-split').getBoundingClientRect().height), beforeHeight);
  await screenshot('execution-traces-long-graph-light', 'light');
  const scale = await evaluate(() => Number(document.querySelector('.wa-trace-graph-surface').dataset.scale));
  await click('[aria-label="放大执行图"]');
  await waitFor(scale => Number(document.querySelector('.wa-trace-graph-surface').dataset.scale) > scale, [scale]);
  await clickText('适应画布', '.wa-trace-graph-controls');
  await waitFor(scale => Math.abs(Number(document.querySelector('.wa-trace-graph-surface').dataset.scale) - scale) < .002, [scale]);
  const camera = await evaluate(() => document.querySelector('.wa-trace-graph-surface').dataset.cameraX);
  await evaluate(() => {
    const el = document.querySelector('.wa-trace-graph-surface'); el.focus();
    el.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  });
  await waitFor(camera => document.querySelector('.wa-trace-graph-surface').dataset.cameraX !== camera, [camera]);
  await clickText('适应画布', '.wa-trace-graph-controls');
  const pointer = await evaluate(() => {
    const el = document.querySelector('.wa-trace-graph-surface'), rect = el.getBoundingClientRect();
    return { x: Math.round(rect.left + 25), y: Math.round(rect.top + 25), camera: Number(el.dataset.cameraX), scale: Number(el.dataset.scale) };
  });
  sendInput({ type: 'mouseDown', x: pointer.x, y: pointer.y, button: 'left', clickCount: 1 });
  sendInput({ type: 'mouseMove', x: pointer.x + 55, y: pointer.y + 30, button: 'left' });
  sendInput({ type: 'mouseUp', x: pointer.x + 55, y: pointer.y + 30, button: 'left', clickCount: 1 });
  await waitFor(camera => Math.abs(Number(document.querySelector('.wa-trace-graph-surface').dataset.cameraX) - camera - 55) < 2, [pointer.camera]);
  sendInput({ type: 'mouseWheel', x: pointer.x + 55, y: pointer.y + 30, deltaX: 0, deltaY: -90 });
  await waitFor(scale => Math.abs(Number(document.querySelector('.wa-trace-graph-surface').dataset.scale) - scale) > .01, [pointer.scale]);
  await waitFor(() => !!document.querySelector('.wa-trace-minimap'));
  await click('[aria-label="点击缩略图定位画布"]');
  await waitFor(() => {
    const surface = document.querySelector('.wa-trace-graph-surface'), svg = document.querySelector('.wa-trace-minimap-canvas svg');
    return Math.abs(Number(surface.dataset.cameraX) - (surface.clientWidth - svg.viewBox.baseVal.width * Number(surface.dataset.scale)) / 2) < 1;
  });
  await screenshot('execution-traces-navigation-dark', 'dark');
  await click('[aria-label="隐藏图谱导航"]'); await waitFor(() => !document.querySelector('.wa-trace-minimap'));
  await click('[aria-label="切换图谱导航"]'); await waitFor(() => !!document.querySelector('.wa-trace-minimap'));
  await click('[aria-label="隐藏图谱导航"]');
  check('the navigation overview appears while exploring, recenters the real viewport, and can be reopened or dismissed');
  await clickText('适应画布', '.wa-trace-graph-controls');
  await clickText('展开画布', '.wa-trace-detail');
  await waitFor(() => getComputedStyle(document.querySelector('.wa-traces-list')).display === 'none');
  await screenshot('execution-traces-focused-dark', 'dark');
  await clickText('收起画布', '.wa-trace-detail');
  check('long traces retain a fixed height with branch pagination, mouse dragging, wheel zoom, keyboard panning, fit and an expanded canvas');
  await click('[data-testid="traces-tab-maintenance"]');
  await waitFor(() => document.querySelectorAll('.wa-trace-list-item').length === 1);
  await click('[data-trace-id="' + ids.maintenance + '"]');
  await waitFor(() => document.querySelector('.wa-trace-detail .wa-trace-badge')?.textContent === '结果待核实');
  check('task categories isolate records, long executions load all steps and uncertain delivery is never shown as completed');
  await click('[data-testid="traces-tab-all"]'); await input('[aria-label="搜索执行轨迹"]', '历史轨迹示例');
  await waitFor(() => document.querySelectorAll('.wa-trace-list-item').length === 1);
  await click('.wa-trace-list-item');
  await waitFor(() => document.querySelector('.wa-trace-detail')?.textContent.includes('历史摘要：当时没有记录完整步骤'));
  await clickText('任务输入与结果', '.wa-trace-detail-tabs');
  await waitFor(() => document.querySelector('.wa-trace-detail')?.textContent.includes('已有历史结果'));
  await input('[aria-label="搜索执行轨迹"]', '');
  await waitFor(() => document.querySelectorAll('.wa-trace-list-item').length > 1);
  await fixture('failNext', { endpoint: 'traces.list' }); await clickText('刷新轨迹');
  await waitFor(() => document.querySelector('[data-testid="execution-traces-page"] [role="alert"]'));
  await clickText('重试读取'); await waitFor(() => document.querySelectorAll('.wa-trace-list-item').length > 1);
  check('historical records are explicitly summaries and failed reads recover without dispatching tasks');
  await click('[data-testid="traces-tab-work"]'); await click('[data-trace-id="' + ids.running + '"]');
  await waitFor(() => document.querySelector('.wa-trace-detail .wa-trace-badge')?.textContent === '执行中');
  await waitFor(() => document.querySelectorAll('.wa-graph-connection[data-running="true"]').length > 0);
  await emulateReducedMotion(true);
  await waitFor(() => matchMedia('(prefers-reduced-motion: reduce)').matches && getComputedStyle(document.querySelector('.wa-graph-connection-signal')).animationName === 'none');
  assert.equal(await evaluate(() => getComputedStyle(document.querySelector('.wa-trace-graph-scene')).transitionDuration), '0s');
  await screenshot('execution-traces-running-reduced-motion-dark', 'dark');
  await emulateReducedMotion(false);
  await fixture('completeTraceFixture');
  await waitFor(() => document.querySelector('.wa-trace-detail .wa-trace-badge')?.textContent === '已完成');
  assert.equal(await evaluate(() => document.querySelectorAll('.wa-graph-connection[data-running="true"]').length), 0);
  check('only active execution branches show activity, and reduced-motion preference disables all animation and camera transitions');
  check('an open running trace follows its actual final outcome through read-only polling');
  await clickText('返回任务列表', '.wa-trace-detail'); await click('[data-testid="traces-tab-conversation"]');
  await click('[data-trace-id="' + ids.conversation + '"]');
  await input('[aria-label="筛选轨迹步骤"]', 'model'); await click('[data-group-id="model"]'); await click('.wa-graph-node-step');
  await waitFor(() => document.querySelector('.wa-trace-inspector')?.textContent.includes('合成系统提示'));
  for (const [width, height, theme] of [[430, 900, 'light'], [320, 850, 'dark']]) {
    resize(width, height); await waitFor(width => innerWidth === width, [width]);
    await assertLayout('execution trace ' + width); await screenshot('execution-trace-' + width + '-' + theme, theme);
    if (await evaluate(() => !!document.querySelector('.wa-trace-inspector'))) await click('[aria-label="关闭步骤详情"]');
    await waitFor(() => [...document.querySelectorAll('.wa-graph-node')].every(node => {
      const bounds = node.getBoundingClientRect();
      return [...node.querySelectorAll('.wa-graph-node-copy strong,.wa-graph-node-kicker,.wa-graph-node-count')].every(label => {
        const rect = label.getBoundingClientRect();
        return !rect.height || rect.top >= bounds.top && rect.bottom <= bounds.bottom && rect.left >= bounds.left && rect.right <= bounds.right;
      });
    }));
    await screenshot('execution-trace-graph-' + width + '-' + theme, theme);
    await clickText('返回任务列表', '.wa-trace-detail'); await assertLayout('execution trace list ' + width); await screenshot('execution-trace-list-' + width + '-' + theme, theme);
    await click('[data-trace-id="' + ids.conversation + '"]'); await waitFor(() => !!document.querySelector('.wa-trace-detail h2'));
    await input('[aria-label="筛选轨迹步骤"]', 'model'); await click('[data-group-id="model"]'); await click('.wa-graph-node-step');
    await waitFor(() => document.querySelector('.wa-trace-inspector')?.textContent.includes('合成系统提示'));
  }
  check('detail and classified record lists fit 1280, 430 and 320 pixel layouts in light and dark themes');
  await fixture('holdNext', { endpoint: 'traces.export' }); await clickText('导出本次轨迹', '.wa-trace-detail');
  await waitFor(async () => (await window.__uiFixture('heldRequest', { endpoint: 'traces.export' })).started);
  await fixture('switchAccount');
  await waitFor(() => document.querySelector('[data-testid="execution-traces-page"]')?.dataset.accountId === 'wxid_ui_other' && !document.querySelector('.wa-trace-detail'));
  await fixture('releaseRequest', { endpoint: 'traces.export' });
  await waitFor(() => document.querySelector('.wa-trace-empty')?.textContent.includes('还没有执行记录'));
  await evaluate(() => new Promise(resolve => setTimeout(resolve, 250)));
  assert.equal(downloads().length, 1); assert.equal(await evaluate(() => document.querySelectorAll('.wa-trace-list-item').length), 0);
  assert(!await evaluate(() => document.querySelector('[data-testid="execution-traces-page"]').textContent.includes('整理今天的讨论')));
  check('account changes clear the selected task and cancel pending exports before an old account download can start');
};
