export function getPersonaPreset(id) { return PERSONA_PRESETS.find(preset => preset.id === id); }

export function personaFromPreset(id, identity) {
  const preset = getPersonaPreset(id);
  if (!preset) throw new Error('所选内置人设不存在，请重新选择');
  const examples = preset.examples.map(example => `场景：${example.scene}\n对方：${example.message}\n回应：${example.reply}`).join('\n\n');
  return {
    name: identity?.name ?? preset.name,
    aliases: [...(identity?.aliases ?? preset.aliases)],
    background: preset.background, personality: preset.personality,
    style: `${preset.style}\n\n语气示例（学习表达方式，不照抄固定台词，也不把示例当成已经发生的对话）：\n${examples}`,
  };
}

export function searchPersonaPresets(query = '', category = 'all') {
  const words = searchText(query).split(' ').filter(Boolean);
  return PERSONA_PRESETS.filter(preset => {
    if (category !== 'all' && preset.category !== category) return false;
    const group = PERSONA_CATEGORIES.find(value => value.id === preset.category);
    const haystack = searchText([preset.name, preset.role, preset.summary, preset.suitableFor, group?.name, ...preset.aliases, ...preset.tags].join(' '));
    return words.every(word => haystack.includes(word));
  });
}
