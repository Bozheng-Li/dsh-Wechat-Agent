export function needsConversationalRewrite(text, request = '') {
  if (/分析|复盘|依据|总结|代码|步骤|清单|列表|逐条|教程|表格|markdown|为什么这样判断|怎么(?:安装|配置|实现)|如何(?:安装|配置|实现)/iu.test(request)) return false;
  return /^(?:按(?:照)?聊天(?:里|中)?能确定的|(?:根据|基于)(?:目前|现有|已有|以上|提供的)?(?:聊天|会话|对话)记录|目前可以确认)[：:，,]?/u.test(text.trim()) ||
    /(?:聊天|会话|对话)记录里(?:没有|没再|未曾).{0,45}(?:不敢瞎编|无法确定|不能确认)/su.test(text) ||
    /(^|\n)#{1,6}\s/u.test(text) || /\*\*[^*\n]+\*\*/u.test(text) ||
    [...text.matchAll(/(?:^|\n)\s*(?:[-*•]\s+|\d+[.)、]\s*)/gu)].length >= 2 ||
    /收到你的问题|让我为你分析|希望这些信息能帮到你|有什么需要随时告诉我/u.test(text);
}
